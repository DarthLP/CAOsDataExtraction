# ---------------------------------------------------------------------------
# Unit conversion helpers
# ---------------------------------------------------------------------------
WEEK = 1.0
DAY  = 1.0 / 5.0       # 5 working days per week
MONTH = 13.0 / 3.0     # 4.333 weeks
YEAR = 52.0

# Use word-boundary anchored patterns so e.g. "monthly" inside "% of monthly
# salary" does NOT match the months pattern. Order matters: weeks first, then
# days, months, years.
DURATION_KEYWORDS = (
    (re.compile(r"\bweek(s|ly)?\b", re.I),               WEEK),  # weeks, week, weekly (working hours)
    (re.compile(r"\bwork\s*weeks?\b", re.I),             WEEK),  # workweek/workweeks (no space breaks \bweek\b)
    (re.compile(r"\bweekly[_\s]*working", re.I),         WEEK),  # weekly_working_hours (underscore breaks \bweek\b)
    (re.compile(r"\b(working\s*)?days?\b", re.I),        DAY),
    (re.compile(r"\bwork\s*days?\b", re.I),              DAY),   # workday/workdays (no space)
    (re.compile(r"\bdays?/shifts?\b", re.I),             DAY),
    (re.compile(r"\b(shifts?|services?)\b", re.I),       DAY),   # a shift/service ~ one worked day
    (re.compile(r"\bmonths?\b", re.I),                   MONTH),
    (re.compile(r"\byears?\b", re.I),                    YEAR),
    (re.compile(r"\bhours?\b", re.I),                    None),  # bare hours: ambiguous; fall back to statutory
)

# leave COVERAGE booleans (the 9 parental/holiday-leave generosity flags; the 3 sickness/care
# top-ups moved to absence on 2026-07-08). Module-level so introspection (advanced_analysis
# factor/FAMD analysis via getattr(module, "BOOLEANS")) can find them — the coverage share in
# main() is built from this same list.
BOOLEANS = [
    "leave_has_leave_enhancements", "leave_has_above_statutory_maternity",
    "leave_paternity_explicitly_above_statutory", "leave_parental_eligibility_present",
    "leave_parental_topup_present", "leave_abortion_present",
    "leave_liberation_day_annual", "leave_liberation_day_lustrum", "leave_extra_seniority_present",
]

PAY_PCT_RE = re.compile(r"%|percent", re.I)
# A unit string that begins with a percent token (possibly after a leading
# float/int — but in practice the value column holds the number, so the unit
# starts with %/percent) is treated as a pay-rate that the extractor put in
# the duration field. "weeks at 100% pay" does NOT match — % is not at start.
PAY_PCT_LEADING_RE = re.compile(r"^\s*(%|percent(?![a-z]))", re.I)


def parse_float(x):
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return None
    s = str(x).strip()
    if not s:
        return None
    try:
        return float(s.replace(",", "."))
    except ValueError:
        return None


def _safe_str(x):
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return ""
    return str(x).strip()


def duration_to_weeks(value, unit) -> float | None:
    """Convert (value, unit) to weeks. Returns None if not parseable.

    IMPORTANT: if the unit string contains a percent token AND no duration
    token, the value is almost certainly a pay-RATE that the extractor
    mis-stored in the duration field (e.g. unit='% of monthly salary',
    value=100). In that case duration is unknown — return None so the
    defensive imputation downstream can kick in (statutory duration @ rate).

    But if the unit contains BOTH a duration token AND a percent token
    (e.g. "weeks at 100% pay"), trust the duration parse.
    """
    v = parse_float(value)
    if v is None:
        return None
    u = _safe_str(unit)
    if not u:
        return None
    # If the unit STARTS with a percent token (e.g. "% of monthly salary
    # for 1st year"), it's a misplaced pay rate, not a duration — even if
    # a downstream duration word appears decoratively.
    if PAY_PCT_LEADING_RE.match(u):
        return None
    for rx, mult in DURATION_KEYWORDS:
        if rx.search(u):
            return None if mult is None else v * mult
    if PAY_PCT_RE.search(u):
        return None  # pay rate stored in duration field; duration unknown
    return None  # unknown unit -> flag as None


def pay_rate(value, unit) -> float | None:
    """Convert pay (value, unit) to a 0-1 fraction. Returns None if not parseable.

    Percent units (any "percent of X" or "% of X") -> value/100.
    Any other unit (including blanks) returns None.
    """
    v = parse_float(value)
    if v is None:
        return None
    u = _safe_str(unit)
    if not PAY_PCT_RE.search(u):
        return None
    # Clamp to [0,1]; some CAOs encode "100%" for full
    return max(0.0, min(1.0, v / 100.0))


# ---------------------------------------------------------------------------
# Statutory floors as a function of ingangsdatum (CAO effective date)
# ---------------------------------------------------------------------------
def statutory_floor(eff_date: date | None) -> dict:
    """Return statutory floor for each leave type as (weeks, rate) tuples.

    Each value is a list of (weeks, rate) segments that together form the
    statutory entitlement at the given date.

    Sources: Wet arbeid en zorg (WAZO), Wet invoering extra geboorteverlof
    (WIEG, 1 Jan 2019 and 1 Jul 2020), Wet betaald ouderschapsverlof
    (Aug 2022).
    """
    d = eff_date or date(2015, 1, 1)

    # Maternity: 16 weeks @ 100% (UWV-paid) throughout the window
    mat = [(16.0, 1.00)]

    # Adoption: 4 weeks @ 100% pre-2019; 6 weeks @ 100% from 1 Jan 2019
    if d >= date(2019, 1, 1):
        ado = [(6.0, 1.00)]
    else:
        ado = [(4.0, 1.00)]

    # Paternity / partner leave:
    # pre-2019: 2 days @ 100% (kraamverlof)
    # 2019-2020-07-01: 1 week (5 working days) @ 100% (WIEG)
    # 2020-07-01+: 1 week @ 100% + 5 weeks @ 70% (additional)
    if d >= date(2020, 7, 1):
        pat = [(1.0, 1.00), (5.0, 0.70)]
    elif d >= date(2019, 1, 1):
        pat = [(1.0, 1.00)]
    else:
        pat = [(2 * DAY, 1.00)]  # 2 working days

    # Parental (Hanna's correction, statutory_timeline.xlsx Leave tab, 2026-07-06):
    # pre-2009:       13 weeks (13x weekly hours) unpaid
    # 2009-2022-08:   26 weeks unpaid
    # 2022-08-02+:    9 weeks @ 70% + 17 weeks unpaid
    if d >= date(2022, 8, 2):
        par = [(9.0, 0.70), (17.0, 0.0)]
    elif d >= date(2009, 1, 1):
        par = [(26.0, 0.0)]
    else:
        par = [(13.0, 0.0)]

    return {"maternity": mat, "paternity": pat, "adoption": ado, "parental": par}


def fre_from_segments(segments):
    """Sum FRE-weeks across a list of (weeks, rate) segments."""
    return sum(w * r for w, r in segments)


def total_weeks_from_segments(segments):
    return sum(w for w, _ in segments)


