"""
Parental-leave generosity index (broad bundle, full-rate-equivalent weeks).

For each (cao_number, id) record in inputs/extracted_data_non_salary.csv,
computes a per-record family-leave generosity index combining maternity,
paternity/partner, adoption, and parental top-up leave into a single
"full-rate-equivalent (FRE) weeks" number.

FRE per leave-type = paid_weeks * 1.00
                   + partially_paid_weeks * (replacement_rate / 100)
                   + unpaid_weeks * 0.00

The index sums FRE across the four leave types.

Two versions are output:
  fre_total_extracted   : sum of what is EXPLICITLY recorded in the CAO
                          (no statutory imputation).
  fre_total_with_statutory: max(extracted, statutory_floor_at_ingangsdatum)
                          per type, then summed. Closer to the actual
                          family-leave package the worker receives.

Companion variables exported alongside the indices, per leave type:
  *_weeks_total : total job-protected weeks (paid + partially_paid + unpaid)
  *_fre         : full-rate equivalent weeks for that type
  *_imputed     : True if statutory floor was used instead of extracted

Units handled:
  Duration units normalised to weeks (DAY=0.2 wks, MONTH=4.333 wks,
  YEAR=52 wks, the various "weekly working hours" / "FTE-equivalent"
  variants treated as weeks ×1).
  Pay-rate units treated as percent of own wage (statutory benefit caps
  ignored - matches the OECD full-rate equivalent convention).

Output: indices/out/parental_leave_index.csv (one row per record).

Run:
  python3 qa/indices/parental_leave_index.py
"""
